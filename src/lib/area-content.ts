export function getAreaDeepGuide(slug: string): AreaDeepGuide | null {
  const area = INITIAL_AREAS.find((item) => item.slug === slug);

  if (!area) {
    return null;
  }

  const guide = guideBySlug[slug];

  return {
    slug: area.slug,
    name: area.name,
    center: area.center,
    profile: guide.profile,
    preEntryChecks: guide.preEntryChecks,
    billingChecks: guide.billingChecks,
    evidenceToKeep: guide.evidenceToKeep,
    reportingFocus: guide.reportingFocus,
    operatorReviewFocus: guide.operatorReviewFocus,
    shareText: guide.shareText,
  };
}

export function getAreaDeepGuides() {
  return INITIAL_AREAS.map((area) => getAreaDeepGuide(area.slug)).filter(
    (guide): guide is AreaDeepGuide => guide !== null,
  );
}
