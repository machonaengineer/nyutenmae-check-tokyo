export function getAreaChecklist(slug: string) {
  const area = INITIAL_AREAS.find((item) => item.slug === slug);

  if (!area) {
    return null;
  }

  return {
    ...area,
    tips: areaTips[slug] ?? ENTRY_CHECK_ITEMS,
  };
}
